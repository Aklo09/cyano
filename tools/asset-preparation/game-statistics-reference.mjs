import { spawn } from 'node:child_process';
import assert from 'node:assert/strict';
import { mkdir, readFile, stat, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { parseArgs } from 'node:util';
import { fileURLToPath } from 'node:url';
import { loadStatisticsCases } from './statistics-cases.mjs';

const root = fileURLToPath(new URL('../../', import.meta.url));
const { values } = parseArgs({ options: { factorio: { type: 'string' }, upstream: { type: 'string', default: path.join(root, 'tools/vendor/fpsr') }, examples: { type: 'string', default: path.join(root, 'Tests/LibraryCoreTests/Fixtures/Blueprints') }, output: { type: 'string' } } });
for (const name of ['factorio', 'upstream', 'output']) if (!values[name]) throw new Error(`Missing --${name}`);
const output = path.resolve(values.output);
const profile = path.join(output, 'profile');
const modDir = path.join(profile, 'mods');
const mod = path.join(modDir, 'fb-statistics-reference');
await mkdir(mod, { recursive: true });
const { cases, inputs } = await loadStatisticsCases(values);
await writeFile(path.join(output, 'cases.json'), JSON.stringify({ inputs, cases }));
await writeFile(path.join(mod, 'info.json'), JSON.stringify({ name: 'fb-statistics-reference', version: '0.1.0', title: 'Local blueprint statistics reference', author: 'Local evaluation', factorio_version: '2.1', dependencies: ['base', 'space-age', 'elevated-rails', 'quality', 'recycler'] }));
await writeFile(path.join(modDir, 'mod-list.json'), JSON.stringify({ mods: ['base', 'space-age', 'elevated-rails', 'quality', 'recycler', 'fb-statistics-reference'].map(name => ({ name, enabled: true })) }));
const jobs = JSON.stringify(cases.map(({ id, string: blueprint, blueprint: data }) => ({ id, blueprint, data })));
await writeFile(path.join(mod, 'jobs.lua'), `return helpers.json_to_table([==[${jobs}]==])\n`);
await writeFile(path.join(mod, 'control.lua'), await readFile(new URL('./statistics-reference.lua', import.meta.url)));
const config = path.join(profile, 'config.ini');
await writeFile(config, `[path]\nread-data=${path.resolve(values.factorio, 'data')}\nwrite-data=${profile}\n`);
const binary = path.join(values.factorio, process.platform === 'darwin' ? 'MacOS/factorio' : 'bin/x64/factorio');
const startedAt = Date.now();
await new Promise((resolve, reject) => {
  const child = spawn(binary, ['--config', config, '--mod-directory', modDir, '--create', path.join(output, 'reference-save.zip'), '--disable-audio', '--map-gen-seed', '1'], { stdio: 'inherit' });
  const timer = setTimeout(() => { child.kill('SIGTERM'); reject(new Error('Game reference exceeded 120 second deadline')); }, 120_000);
  child.on('error', error => { clearTimeout(timer); reject(error); });
  child.on('exit', (code, signal) => { clearTimeout(timer); code === 0 ? resolve() : reject(new Error(`Factorio exited ${code} (${signal})`)); });
});
const referencePath = path.join(profile, 'script-output/statistics-reference.json');
assert.ok((await stat(referencePath)).mtimeMs >= startedAt, 'Stale game reference output');
const reference = JSON.parse(await readFile(referencePath, 'utf8'));
const installed = JSON.parse(await readFile(path.join(values.factorio, 'data/base/info.json'), 'utf8'));
assert.equal(reference.gameVersion, installed.version, 'Reference/game version mismatch');
assert.equal(reference.cases.length, cases.length, 'Incomplete game reference');
assert.equal(Object.keys(reference.geometryErrors).length, 0, 'Missing engine geometry');
await writeFile(path.join(output, 'reference.json'), JSON.stringify(reference, null, 2) + '\n');
console.log(`Game reference: ${reference.gameVersion}; ${reference.cases.length} blueprints; ${Object.keys(reference.entities).length} entity prototypes`);
